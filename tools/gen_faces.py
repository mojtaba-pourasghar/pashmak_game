INK = '#2B3742'
WHITE = '#FFFDF8'


def p(fill, d, alpha=None):
    a = ' android:fillAlpha="%s"' % alpha if alpha else ''
    return '    <path android:fillColor="%s"%s android:pathData="%s" />\n' % (fill, a, d)


def stroke(color, d, width=0.85, cap='round'):
    return ('    <path android:fillColor="#00000000" android:strokeColor="%s"\n'
            '        android:strokeWidth="%s" android:strokeLineCap="%s"\n'
            '        android:pathData="%s" />\n' % (color, width, cap, d))


def circle(fill, cx, cy, r, alpha=None):
    return p(fill, 'M%g,%g m-%g,0 a%g,%g 0 1,0 %g,0 a%g,%g 0 1,0 -%g,0'
             % (cx, cy, r, r, r, r * 2, r, r, r * 2), alpha)


def ellipse(fill, cx, cy, rx, ry, alpha=None):
    return p(fill, 'M%g,%g m-%g,0 a%g,%g 0 1,0 %g,0 a%g,%g 0 1,0 -%g,0'
             % (cx, cy, rx, rx, ry, rx * 2, rx, ry, rx * 2), alpha)


def eye(cx, cy, r=1.0):
    return (circle(INK, cx, cy, r)
            + circle(WHITE, cx - r * 0.33, cy - r * 0.35, r * 0.4))


def smile(cx, cy, w=1.4):
    return stroke(INK, 'M%g,%g q%g,%g %g,0' % (cx - w / 2, cy, w / 2, w * 0.8, w))


