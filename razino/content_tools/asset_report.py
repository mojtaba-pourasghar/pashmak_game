#!/usr/bin/env python3
"""Generates docs/ASSETS.md: every art and audio file the content references,
and whether it exists yet.

This is produced from the chapter data rather than written by hand, so the
list cannot drift from what the game actually asks for, and nothing can be
quietly marked done.

    python3 content_tools/asset_report.py
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

BG_SPEC = """Format WebP (fall back to PNG), sRGB. Two sizes per background:
2048x1152 for tablets and 1280x720 for phones; the engine letterboxes
between aspect ratios rather than cropping the important part of the
scene. Painted in the style fixed in docs/ART_DIRECTION.md: 2D painted
with clean edges and soft shading, warm palette for safe places and a
cooler, more contrasted palette for mystery locations."""

VO_SPEC = """Ogg Vorbis, mono, 44.1 kHz, target -16 LUFS, room tone trimmed to
under 150 ms at both ends. One file per line id. The same voice must play a
character across all ten chapters."""


def load_chapters() -> dict:
    out = {}
    for d in sorted((ROOT / "content").glob("season_*")):
        f = d / "story.json"
        if f.exists():
            out[d.name] = json.loads(f.read_text(encoding="utf-8"))
    return out


def exists_bg(chapter: str, bg: str) -> bool:
    return any(p.exists() for p in [
        ROOT / "content" / chapter / "backgrounds" / f"{bg}.webp",
        ROOT / "content" / chapter / "backgrounds" / f"{bg}.png",
        ROOT / "assets" / "art" / "backgrounds" / f"{bg}.webp",
        ROOT / "assets" / "art" / "backgrounds" / f"{bg}.png",
    ])


def exists_vo(chapter: str, audio_id: str) -> bool:
    return any(p.exists() for p in [
        ROOT / "content" / chapter / "audio" / "vo" / f"{audio_id}.ogg",
        ROOT / "assets" / "audio" / "vo" / f"{audio_id}.ogg",
    ])


def main() -> int:
    chapters = load_chapters()
    backgrounds: dict[str, set] = defaultdict(set)
    voice: dict[str, list] = defaultdict(list)
    music: set[str] = set()
    sfx: set[str] = set()
    speakers: dict[str, int] = defaultdict(int)

    for cid, data in chapters.items():
        for scene in data.get("scenes", []):
            if scene.get("background_id"):
                backgrounds[cid].add(scene["background_id"])
            if scene.get("music_id"):
                music.add(scene["music_id"])
            for beat in (scene.get("cinematic") or {}).get("beats", []):
                if beat.get("background_id"):
                    backgrounds[cid].add(beat["background_id"])
                if beat.get("audio_id"):
                    voice[cid].append((beat["audio_id"], "nar", beat.get("text", "")))
            for line in scene.get("dialogue", []):
                if line.get("audio_id"):
                    voice[cid].append((line["audio_id"], line.get("speaker_id", "?"), line.get("text", "")))
                    speakers[line.get("speaker_id", "?")] += 1
            for eff_list in [scene.get("on_enter", [])]:
                for eff in eff_list or []:
                    if "play_sfx" in eff:
                        sfx.add(eff["play_sfx"])
            for inter in scene.get("interactions", []):
                for eff in inter.get("effects", []) or []:
                    if "play_sfx" in eff:
                        sfx.add(eff["play_sfx"])
            for ch in scene.get("choices", []):
                for eff in ch.get("effects", []) or []:
                    if "play_sfx" in eff:
                        sfx.add(eff["play_sfx"])
            p = scene.get("puzzle") or {}
            for key in ("on_solve", "on_skip"):
                for eff in p.get(key, []) or []:
                    if "play_sfx" in eff:
                        sfx.add(eff["play_sfx"])

    total_bg = sum(len(v) for v in backgrounds.values())
    missing_bg = sum(1 for cid, ids in backgrounds.items() for b in ids if not exists_bg(cid, b))
    total_vo = sum(len(v) for v in voice.values())
    missing_vo = sum(1 for cid, lines in voice.items() for a, _, _ in lines if not exists_vo(cid, a))

    lines = []
    w = lines.append
    w("# دارایی‌ها — Asset inventory\n")
    w("**Generated by `content_tools/asset_report.py`. Do not edit by hand.**\n")
    w("Every image and sound the shipped chapter data references, and whether the")
    w("file exists in this repository yet. A row marked ❌ has no file: the game")
    w("falls back to a clearly-marked placeholder for images, and to an estimated")
    w("reading time with a visible «صدای این خط هنوز ضبط نشده است» notice for")
    w("voice lines. Neither fallback is a deliverable.\n")
    w("## Summary\n")
    w("| | referenced | present | missing |")
    w("|---|---:|---:|---:|")
    w(f"| Backgrounds | {total_bg} | {total_bg - missing_bg} | {missing_bg} |")
    w(f"| Voice lines | {total_vo} | {total_vo - missing_vo} | {missing_vo} |")
    w(f"| Music tracks | {len(music)} | 0 | {len(music)} |")
    w(f"| Sound effects | {len(sfx)} | 0 | {len(sfx)} |")
    w("")
    w("### What IS in the repository\n")
    w("- **Vazirmatn** (SIL OFL 1.1), the Persian typeface, with its licence.")
    w("- **The player avatar and the whole cast**, drawn as original vector art")
    w("  in `scripts/ui/avatar_portrait.gd` and `scripts/ui/character_figure.gd`.")
    w("  These are real, parametric and consistent at any size — not placeholders —")
    w("  though hand-painted sheets would replace them for the shipping look.")
    w("- **The app icon**, an original mark in `assets/art/ui/icon.svg`.\n")
    w("### Background specification\n")
    w("```")
    w(BG_SPEC)
    w("```\n")
    w("### Voice specification\n")
    w("```")
    w(VO_SPEC)
    w("```\n")
    w("## Backgrounds by chapter\n")
    for cid in sorted(backgrounds):
        title = chapters[cid].get("title", cid)
        w(f"### {cid} — {title}\n")
        w("| asset id | file | prompt / brief |")
        w("|---|---|---|")
        for bg in sorted(backgrounds[cid]):
            mark = "✅" if exists_bg(cid, bg) else "❌"
            place = bg.replace(f"BG_{cid.replace('season_', 'S')}_", "").replace("_", " ").title()
            brief = (f"{chapters[cid].get('primary_environment', '')} — {place}. "
                     f"Razino's painted 2D style, {chapters[cid].get('core_mechanic', '')} scene.")
            w(f"| `{bg}` | {mark} `content/{cid}/backgrounds/{bg}.webp` | {brief} |")
        w("")
    w("## Voice lines\n")
    w("Recording order is by chapter, then by speaker, so a session covers one")
    w("voice at a time.\n")
    w("| speaker | lines |")
    w("|---|---:|")
    for s, n in sorted(speakers.items(), key=lambda kv: -kv[1]):
        w(f"| `{s}` | {n} |")
    w("")
    for cid in sorted(voice):
        w(f"<details><summary><code>{cid}</code> — {len(voice[cid])} lines</summary>\n")
        w("| audio id | speaker | line | file |")
        w("|---|---|---|---|")
        for audio_id, speaker, text in voice[cid]:
            mark = "✅" if exists_vo(cid, audio_id) else "❌"
            safe = text.replace("|", "/").strip()
            w(f"| `{audio_id}` | `{speaker}` | {safe} | {mark} |")
        w("\n</details>\n")
    w("## Music and effects\n")
    w("| id | kind | file |")
    w("|---|---|---|")
    for m in sorted(music):
        w(f"| `{m}` | music | ❌ `assets/audio/music/{m}.ogg` |")
    for s in sorted(sfx):
        w(f"| `{s}` | effect | ❌ `assets/audio/sfx/{s}.ogg` |")
    w("")

    out = ROOT / "docs" / "ASSETS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")
    print(f"  backgrounds: {total_bg - missing_bg}/{total_bg} present")
    print(f"  voice lines: {total_vo - missing_vo}/{total_vo} present")
    print(f"  music: 0/{len(music)}   effects: 0/{len(sfx)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
